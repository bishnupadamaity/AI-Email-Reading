import { type AnalysisDetail } from '@email-ai/contracts';
import { Braces, CircleCheck, Flag, Pencil, Sparkles, SquareCheck } from 'lucide-react';
import { useMemo } from 'react';
import {
  FIELD_GROUP_LABELS,
  readFields,
  type FieldGroup,
  type FieldReading,
} from '../../lib/extraction';
import { humanizeEnum } from '../../lib/format';
import { Badge } from '../ui/Badge';
import { CopyButton } from '../ui/CopyButton';
import { UnsupportedButton } from '../ui/Unsupported';
import { ConflictCard } from './ConflictCard';
import { FieldRow } from './FieldRow';

const GROUP_ORDER: readonly FieldGroup[] = [
  'parties',
  'identifiers',
  'route',
  'carrier',
  'schedule',
];

/**
 * The AI's reading of one email.
 *
 * Everything in this panel is model output. There is no human-approved layer to
 * contrast it with, because the API cannot store one — so the panel is labelled
 * as unreviewed AI output throughout, and the review actions are visibly
 * disabled instead of pretending to save.
 */
export function ExtractionPanel({
  analysis,
  selectedField,
  onSelectField,
  locatedKeys,
}: {
  analysis: AnalysisDetail;
  selectedField: string | null;
  onSelectField: (key: string) => void;
  locatedKeys?: ReadonlySet<string>;
}) {
  const extraction = analysis.extractedData;

  const grouped = useMemo(() => {
    if (!extraction) return new Map<FieldGroup, FieldReading[]>();
    const map = new Map<FieldGroup, FieldReading[]>();
    for (const field of readFields(extraction)) {
      const list = map.get(field.group) ?? [];
      list.push(field);
      map.set(field.group, list);
    }
    return map;
  }, [extraction]);

  if (!extraction) return null;

  const conflictCount = extraction.conflicts.length;
  const missingCount = extraction.missingFields.length;

  return (
    <div>
      <div className="panel__head extraction__head">
        <div className="inline inline--sm">
          <Sparkles size={14} aria-hidden="true" style={{ color: 'var(--accent)' }} />
          <h2 className="panel__title">AI extraction</h2>
          <Badge tone="accent">Unreviewed</Badge>
        </div>
        <div className="inline inline--sm">
          <CopyButton
            value={JSON.stringify(extraction, null, 2)}
            label="Copy all extracted data as JSON"
            size="xs"
            variant="ghost"
            withText="JSON"
          />
        </div>
      </div>

      <div className="panel__body stack stack--sm">
        <div className="inline inline--sm">
          <Badge tone="info" size="lg">
            {humanizeEnum(extraction.classification)}
          </Badge>
          <span className="muted" style={{ fontSize: 'var(--text-sm)' }}>
            Classification
          </span>
        </div>
        <p style={{ fontSize: 'var(--text-md)', lineHeight: 'var(--leading-relaxed)' }}>
          {extraction.summary}
        </p>
      </div>

      {/* A standing reminder of what this panel is: model output that no human
          has checked. The disabled review actions below say the same thing. */}
      <div className="extraction__provenance">
        <span>
          Generated by {analysis.modelName ?? 'the configured model'} · not human-verified
        </span>
        <span className="inline inline--sm">
          {conflictCount > 0 ? (
            <Badge tone="danger">
              {conflictCount} {conflictCount === 1 ? 'conflict' : 'conflicts'}
            </Badge>
          ) : null}
          {missingCount > 0 ? <Badge tone="warning">{missingCount} missing</Badge> : null}
          {conflictCount === 0 && missingCount === 0 ? (
            <Badge tone="success">No flags</Badge>
          ) : null}
        </span>
      </div>

      <div className="field-group__head">
        <span>Extracted fields</span>
        <span>Select a field to see its evidence</span>
      </div>

      <div className="fields">
        {GROUP_ORDER.map((group) => {
          const fields = grouped.get(group);
          if (!fields?.length) return null;

          return (
            <div key={group}>
              <div className="field-group__head">
                <span>{FIELD_GROUP_LABELS[group]}</span>
              </div>
              {fields.map((field) => (
                <FieldRow
                  key={field.key}
                  field={field}
                  selected={selectedField === field.key}
                  onSelect={onSelectField}
                  evidenceLocated={
                    field.evidence ? (locatedKeys?.has(field.key) ?? undefined) : undefined
                  }
                />
              ))}
            </div>
          );
        })}
      </div>

      {extraction.conflicts.length > 0 ? (
        <>
          <div className="field-group__head">
            <span>Conflicts · {extraction.conflicts.length}</span>
          </div>
          <div className="panel__body stack stack--sm">
            {extraction.conflicts.map((conflict) => (
              <ConflictCard
                key={conflict.field}
                conflict={conflict}
                footer="No value was chosen: the field is stored as null and the API has no endpoint to record a resolution."
              />
            ))}
          </div>
        </>
      ) : null}

      {extraction.missingFields.length > 0 ? (
        <>
          <div className="field-group__head">
            <span>Reported missing · {extraction.missingFields.length}</span>
          </div>
          <div className="panel__body">
            <dl className="dl">
              {extraction.missingFields.map((missing) => (
                <div key={missing.field} style={{ display: 'contents' }}>
                  <dt>{missing.field}</dt>
                  <dd>{missing.reason ?? 'No reason given'}</dd>
                </div>
              ))}
            </dl>
          </div>
        </>
      ) : null}

      <div className="field-group__head">
        <span>Review actions</span>
      </div>
      <div className="panel__body stack stack--sm">
        <div className="inline inline--sm">
          <UnsupportedButton capability="reviewDecision" icon={<SquareCheck size={12} />}>
            Mark reviewed
          </UnsupportedButton>
          <UnsupportedButton capability="reviewDecision" icon={<CircleCheck size={12} />}>
            Approve extraction
          </UnsupportedButton>
          <UnsupportedButton capability="fieldEdit" icon={<Pencil size={12} />}>
            Edit a value
          </UnsupportedButton>
          <UnsupportedButton capability="reviewDecision" icon={<Flag size={12} />}>
            Flag as incorrect
          </UnsupportedButton>
        </div>
        <p className="muted" style={{ fontSize: 'var(--text-sm)' }}>
          These four actions are disabled because no endpoint stores a review decision or a
          corrected value. Running and retrying analysis, and copying values, are real.
        </p>
        <div className="inline inline--sm">
          <Braces size={12} aria-hidden="true" className="muted" />
          <span className="muted" style={{ fontSize: 'var(--text-sm)' }}>
            Analysis <code className="inline-code">{analysis.id}</code>
          </span>
          <CopyButton value={analysis.id} label="Copy analysis id" />
        </div>
      </div>
    </div>
  );
}
